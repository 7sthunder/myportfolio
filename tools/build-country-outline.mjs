// Builds the particle-map silhouette used by the "Based in India" section.
//
// Downloads an official-boundary GeoJSON, projects it (Web Mercator), simplifies the rings and
// writes a compact SVG path to src/data/countryOutline.js. Run once; the result is committed.
//
// Usage: node tools/build-country-outline.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// DataMeet's composite country layer follows the Survey of India boundary (full J&K, Ladakh,
// Andaman & Nicobar), which is the map an Indian portfolio should show.
const SOURCE = 'https://raw.githubusercontent.com/datameet/maps/master/Country/india-composite.geojson';

const TOLERANCE = 0.0009; // simplification, in normalised units (1 = silhouette height)
const MIN_AREA = 4e-5; // drops specks; keeps the mainland and the larger islands
const PRECISION = 4;

const radians = (deg) => (deg * Math.PI) / 180;
const mercatorY = (lat) => Math.log(Math.tan(Math.PI / 4 + radians(lat) / 2));

function* rings(geometry) {
  if (!geometry) return;
  if (geometry.type === 'Polygon') yield* geometry.coordinates;
  else if (geometry.type === 'MultiPolygon') for (const poly of geometry.coordinates) yield* poly;
  else if (geometry.type === 'GeometryCollection') for (const g of geometry.geometries) yield* rings(g);
}

/** Douglas-Peucker on a closed ring. */
function simplify(points, tolerance) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  const t2 = tolerance * tolerance;
  while (stack.length) {
    const [first, last] = stack.pop();
    if (last - first < 2) continue;
    const [ax, ay] = points[first];
    const [bx, by] = points[last];
    const dx = bx - ax;
    const dy = by - ay;
    const len2 = dx * dx + dy * dy;
    let index = -1;
    let max = t2;
    for (let i = first + 1; i < last; i++) {
      const [px, py] = points[i];
      let d2;
      if (len2 === 0) {
        d2 = (px - ax) ** 2 + (py - ay) ** 2;
      } else {
        const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2));
        d2 = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2;
      }
      if (d2 > max) {
        max = d2;
        index = i;
      }
    }
    if (index > 0) {
      keep[index] = 1;
      stack.push([first, index], [index, last]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const ringArea = (points) => {
  let sum = 0;
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    sum += points[j][0] * points[i][1] - points[i][0] * points[j][1];
  }
  return Math.abs(sum) / 2;
};

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${response.status} ${SOURCE}`);
const geojson = await response.json();

const projected = [];
for (const feature of geojson.features ?? [geojson]) {
  for (const ring of rings(feature.geometry)) {
    projected.push(ring.map(([lon, lat]) => [radians(lon), mercatorY(lat)]));
  }
}

let minX = Infinity;
let maxX = -Infinity;
let minY = Infinity;
let maxY = -Infinity;
for (const ring of projected) {
  for (const [x, y] of ring) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
}

// Normalise to height 1 with y pointing down (SVG convention); width follows the aspect ratio.
const scale = 1 / (maxY - minY);
const width = (maxX - minX) * scale;

const parts = [];
let points = 0;
for (const ring of projected) {
  const normalised = ring.map(([x, y]) => [(x - minX) * scale, (maxY - y) * scale]);
  const simplified = simplify(normalised, TOLERANCE);
  if (simplified.length < 4 || ringArea(simplified) < MIN_AREA) continue;
  points += simplified.length;
  const d = simplified.map(([x, y]) => `${x.toFixed(PRECISION)} ${y.toFixed(PRECISION)}`);
  parts.push(`M${d[0]}L${d.slice(1).join('L')}Z`);
}

const out = `// Generated by tools/build-country-outline.mjs - do not edit by hand.
// Source: ${SOURCE}
// Web Mercator, normalised to height 1 with y pointing down (SVG convention).
export const countryOutline = {
  name: 'India',
  width: ${width.toFixed(4)},
  height: 1,
  path: '${parts.join('')}',
};
`;

const target = join(root, 'src', 'data', 'countryOutline.js');
writeFileSync(target, out);
console.log(`${target}: ${parts.length} rings, ${points} points, ${(out.length / 1024).toFixed(1)} KB`);
